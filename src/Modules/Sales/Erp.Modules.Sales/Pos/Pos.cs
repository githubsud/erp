/// <summary>
/// Retail point of sale. Each sale posts at once: cash (net of change) and card to the register's accounts, revenue by item group,
/// and stock issued at weighted-average cost. Closing a shift compares counted cash with what the till should hold and posts the
/// difference to cash over and short.
/// </summary>
internal sealed class PosService(ErpDbContext db, ITenantContext tenant, INumberingService numbering, IInventoryQueries inventory, IStockService stock,
    IPostingService posting, IClock clock, IFinanceQueries finance)
{
    public const string SourceType = "pos_sale";
    public const string ShiftSourceType = "pos_shift";

    public async Task<PosRegister> SaveRegisterAsync(Guid? id, RegisterRequest r, CancellationToken ct)
    {
        var (en, ar) = Bilingual.Require(r.NameEn, r.NameAr);
        if (await inventory.GetWarehouseAsync(r.WarehouseId, ct) is not { IsActive: true }) throw new NotFoundException("Warehouse", r.WarehouseId);
        foreach (var accountId in new[] { r.CashAccountId, r.CardAccountId })
            if (await finance.FindPostableAccountAsync(accountId, ct) is null) throw new NotFoundException("Account", accountId);
        var register = id is null
            ? db.Add(new PosRegister { CompanyId = tenant.RequireCompanyId(), Code = Guard.Required(r.Code, "code").ToUpperInvariant(), NameEn = en, NameAr = ar }).Entity
            : await db.Set<PosRegister>().SingleOrDefaultAsync(x => x.Id == id && x.CompanyId == tenant.RequireCompanyId(), ct) ?? throw new NotFoundException("Register", id);
        register.NameEn = en;
        register.NameAr = ar;
        register.WarehouseId = r.WarehouseId;
        register.CashAccountId = r.CashAccountId;
        register.CardAccountId = r.CardAccountId;
        register.IsActive = r.IsActive;
        await db.SaveChangesAsync(ct);
        return register;
    }

    public Task<PosShift> OpenShiftAsync(OpenShiftRequest r, CancellationToken ct) =>
        db.InTransactionAsync(async token =>
        {
            var register = await RegisterAsync(r.RegisterId, token);
            if (!register.IsActive) throw new BusinessRuleException("sal.register_inactive", "This register is not in use.", "نقطة البيع هذه غير مستخدمة.");
            if (await db.Set<PosShift>().AnyAsync(s => s.RegisterId == register.Id && s.Status == ShiftStatus.Open, token))
                throw new ConflictException("sal.shift_open", "This register already has an open shift.", "يوجد وردية مفتوحة لنقطة البيع هذه.");
            if (r.OpeningFloat < 0) throw new BusinessRuleException("sal.float", "The opening float cannot be negative.", "لا يمكن أن يكون رصيد الافتتاح سالباً.");
            var shift = new PosShift
            {
                RegisterId = register.Id, ShiftNo = await numbering.NextAsync(ShiftSourceType, "SH", clock.Today, ct: token), CashierUserId = tenant.ActingUserId,
                OpenedAt = clock.UtcNow, OpeningFloat = Money.Round(r.OpeningFloat), BusinessDate = clock.Today
            };
            db.Add(shift);
            await db.SaveChangesAsync(token);
            return shift;
        }, ct);

    public Task<PosSale> SellAsync(PosSaleRequest r, CancellationToken ct) =>
        db.InTransactionAsync(async token =>
        {
            var existing = await db.Set<PosSale>().Include(s => s.Lines).SingleOrDefaultAsync(s => s.ClientId == r.ClientId, token);
            if (existing is not null) return existing;
            var (shift, register) = await OpenShiftAsync(r.ShiftId, token);
            if (r.Lines is not { Count: > 0 } || r.Lines.Any(l => l.Quantity <= 0))
                throw new BusinessRuleException("sal.pos_lines", "Add items with positive quantities.", "أضف أصنافاً بكميات موجبة.");
            if (r.Cash < 0 || r.Card < 0) throw new BusinessRuleException("sal.pos_payment", "Payments cannot be negative.", "لا يمكن أن تكون المدفوعات سالبة.");
            var items = await inventory.GetItemsAsync(r.Lines.Select(l => l.ItemId), token);
            var sale = new PosSale
            {
                ShiftId = shift.Id, ReceiptNo = await numbering.NextAsync(SourceType, $"{register.Code}-", clock.Today, ct: token), ClientId = r.ClientId,
                SoldAt = r.SoldAt ?? clock.UtcNow, CustomerName = Clean(r.CustomerName), CustomerPhone = Clean(r.CustomerPhone)
            };
            var no = 0;
            foreach (var l in r.Lines)
            {
                if (!items.TryGetValue(l.ItemId, out var item) || !item.IsActive) throw new NotFoundException("Item", l.ItemId);
                var price = l.UnitPrice ?? item.SalesPrice ?? throw new BusinessRuleException("sal.price_missing", $"{item.Sku} has no sales price.", $"لا يوجد سعر بيع للصنف {item.Sku}.");
                var amount = SalesRules.LineAmount(l.Quantity, price, l.DiscountPercent);
                sale.Lines.Add(new PosSaleLine
                {
                    PosSaleId = sale.Id, LineNo = ++no, ItemId = item.Id, Quantity = l.Quantity, UnitPrice = price, DiscountPercent = l.DiscountPercent, Amount = amount
                });
                sale.DiscountTotal += SalesRules.LineDiscount(l.Quantity, price, amount);
            }
            sale.Total = sale.Lines.Sum(l => l.Amount);
            var card = Money.Round(r.Card);
            var cash = Money.Round(r.Cash);
            if (card > sale.Total) throw new BusinessRuleException("sal.pos_card", "The card amount is more than the total.", "مبلغ البطاقة أكبر من الإجمالي.");
            if (cash + card < sale.Total)
                throw new BusinessRuleException("sal.pos_short", $"{sale.Total - cash - card:N2} is still to be paid.", $"المتبقي للدفع {sale.Total - cash - card:N2}.");
            sale.CardAmount = card;
            sale.ChangeGiven = cash + card - sale.Total;
            sale.CashAmount = cash;
            db.Add(sale);

            var builder = new PostingBuilder();
            var stockLines = sale.Lines.Where(l => items[l.ItemId].Type == ItemType.Stock).ToList();
            if (stockLines.Count > 0)
            {
                var results = await stock.PostAsync(new StockPosting(SourceType, sale.Id, sale.ReceiptNo, DateOnly.FromDateTime(sale.SoldAt.ToOffset(TimeSpan.FromHours(3)).DateTime),
                    stockLines.Select(l => new StockLine(l.ItemId, register.WarehouseId, -l.Quantity, SourceLineId: l.Id)).ToList()), token);
                foreach (var x in results)
                {
                    sale.Lines.Single(l => l.Id == x.SourceLineId).Cost = -x.Value;
                    builder.Add(AccountRoles.CostOfSales, x.ItemGroupId, -x.Value);
                    builder.Add(AccountRoles.Inventory, x.ItemGroupId, x.Value);
                }
            }
            sale.Cost = sale.Lines.Sum(l => l.Cost);
            foreach (var l in sale.Lines)
                builder.Add(items[l.ItemId].Type == ItemType.Service ? AccountRoles.ServiceRevenue : AccountRoles.SalesRevenue, items[l.ItemId].ItemGroupId, -l.Amount);
            var lines = builder.Lines();
            if (sale.Total - card > 0) lines.Add(new PostingLine { AccountId = register.CashAccountId, Side = PostingSide.Debit, Amount = sale.Total - card });
            if (card > 0) lines.Add(new PostingLine { AccountId = register.CardAccountId, Side = PostingSide.Debit, Amount = card });
            sale.JournalEntryId = (await posting.PostAsync(new PostingRequest
            {
                SourceType = SourceType, SourceId = sale.Id, SourceNo = sale.ReceiptNo, PostingDate = shift.BusinessDate,
                MemoEn = $"POS sale {sale.ReceiptNo}", MemoAr = $"بيع نقطة البيع {sale.ReceiptNo}", Lines = lines
            }, token)).JournalEntryId;
            await db.SaveChangesAsync(token);
            return sale;
        }, ct);

    /// <summary>Goods brought back: stock returns at the cost it left with; cash (or card) is paid back.</summary>
    public Task<PosSale> RefundAsync(PosRefundRequest r, CancellationToken ct) =>
        db.InTransactionAsync(async token =>
        {
            var existing = await db.Set<PosSale>().Include(s => s.Lines).SingleOrDefaultAsync(s => s.ClientId == r.ClientId, token);
            if (existing is not null) return existing;
            var (shift, register) = await OpenShiftAsync(r.ShiftId, token);
            var original = await db.Set<PosSale>().Include(s => s.Lines).SingleOrDefaultAsync(s => s.Id == r.SaleId && s.RefundOfId == null, token)
                           ?? throw new NotFoundException("POS sale", r.SaleId);
            var refunded = await (from l in db.Set<PosSaleLine>()
                                  join s in db.Set<PosSale>() on l.PosSaleId equals s.Id
                                  where s.RefundOfId == original.Id
                                  select new { l.RefundOfLineId, l.Quantity }).ToListAsync(token);
            var items = await inventory.GetItemsAsync(original.Lines.Select(l => l.ItemId), token);
            var refund = new PosSale
            {
                ShiftId = shift.Id, ReceiptNo = await numbering.NextAsync(SourceType, $"{register.Code}-R", clock.Today, ct: token), ClientId = r.ClientId,
                SoldAt = clock.UtcNow, RefundOfId = original.Id, CustomerName = original.CustomerName
            };
            var no = 0;
            foreach (var x in r.Lines)
            {
                var line = original.Lines.SingleOrDefault(l => l.Id == x.SaleLineId) ?? throw new NotFoundException("Sale line", x.SaleLineId);
                var already = -refunded.Where(f => f.RefundOfLineId == line.Id).Sum(f => f.Quantity);
                if (x.Quantity <= 0 || already + x.Quantity > line.Quantity)
                    throw new BusinessRuleException("sal.pos_over_refund", $"Only {line.Quantity - already:0.##} can still be refunded.", $"الكمية القابلة للاسترداد {line.Quantity - already:0.##} فقط.");
                var amount = x.Quantity == line.Quantity ? line.Amount : Money.Round(line.Amount * x.Quantity / line.Quantity);
                refund.Lines.Add(new PosSaleLine
                {
                    PosSaleId = refund.Id, LineNo = ++no, ItemId = line.ItemId, Quantity = -x.Quantity, UnitPrice = line.UnitPrice, DiscountPercent = line.DiscountPercent,
                    Amount = -amount, Cost = -Money.Round(line.Cost * x.Quantity / line.Quantity), RefundOfLineId = line.Id
                });
            }
            refund.Total = refund.Lines.Sum(l => l.Amount);
            if (r.ToCard) refund.CardAmount = refund.Total;
            else refund.CashAmount = refund.Total;
            refund.Cost = refund.Lines.Sum(l => l.Cost);
            db.Add(refund);

            var builder = new PostingBuilder();
            var stockLines = refund.Lines.Where(l => items[l.ItemId].Type == ItemType.Stock).ToList();
            if (stockLines.Count > 0)
            {
                var results = await stock.PostAsync(new StockPosting(SourceType, refund.Id, refund.ReceiptNo, shift.BusinessDate,
                    stockLines.Select(l => new StockLine(l.ItemId, register.WarehouseId, -l.Quantity, -l.Cost / -l.Quantity, l.Id)).ToList()), token);
                foreach (var x in results)
                {
                    builder.Add(AccountRoles.Inventory, x.ItemGroupId, x.Value);
                    builder.Add(AccountRoles.CostOfSales, x.ItemGroupId, -x.Value);
                }
            }
            foreach (var l in refund.Lines)
                builder.Add(items[l.ItemId].Type == ItemType.Service ? AccountRoles.ServiceRevenue : AccountRoles.SalesRevenue, items[l.ItemId].ItemGroupId, -l.Amount);
            var lines = builder.Lines();
            lines.Add(new PostingLine { AccountId = r.ToCard ? register.CardAccountId : register.CashAccountId, Side = PostingSide.Credit, Amount = -refund.Total });
            refund.JournalEntryId = (await posting.PostAsync(new PostingRequest
            {
                SourceType = SourceType, SourceId = refund.Id, SourceNo = refund.ReceiptNo, PostingDate = shift.BusinessDate,
                MemoEn = $"POS refund {refund.ReceiptNo} of {original.ReceiptNo}", MemoAr = $"استرداد {refund.ReceiptNo} من {original.ReceiptNo}", Lines = lines
            }, token)).JournalEntryId;
            await db.SaveChangesAsync(token);
            return refund;
        }, ct);

    public Task<PosShift> CloseShiftAsync(Guid id, CloseShiftRequest r, CancellationToken ct) =>
        db.InTransactionAsync(async token =>
        {
            var (shift, register) = await OpenShiftAsync(id, token);
            var expected = shift.OpeningFloat + await CashTakenAsync(shift.Id, token);
            shift.ExpectedCash = expected;
            shift.CountedCash = Money.Round(r.CountedCash);
            shift.Difference = shift.CountedCash - expected;
            shift.Status = ShiftStatus.Closed;
            shift.ClosedAt = clock.UtcNow;
            shift.Notes = Clean(r.Notes);
            if (shift.Difference != 0)
            {
                var diff = shift.Difference.Value;
                shift.ClosingEntryId = (await posting.PostAsync(new PostingRequest
                {
                    SourceType = ShiftSourceType, SourceId = shift.Id, SourceNo = shift.ShiftNo, PostingDate = shift.BusinessDate,
                    MemoEn = $"Cash {(diff > 0 ? "over" : "short")} at close of shift {shift.ShiftNo}", MemoAr = $"فرق نقدية عند إغلاق الوردية {shift.ShiftNo}",
                    Lines =
                    [
                        new PostingLine { AccountId = register.CashAccountId, Side = diff > 0 ? PostingSide.Debit : PostingSide.Credit, Amount = Math.Abs(diff) },
                        new PostingLine { AccountRole = AccountRoles.CashOverShort, Side = diff > 0 ? PostingSide.Credit : PostingSide.Debit, Amount = Math.Abs(diff) }
                    ]
                }, token)).JournalEntryId;
            }
            await db.SaveChangesAsync(token);
            return shift;
        }, ct);

    public async Task<ZReport> ZReportAsync(Guid shiftId, CancellationToken ct)
    {
        var shift = await db.Set<PosShift>().AsNoTracking().SingleOrDefaultAsync(s => s.Id == shiftId, ct) ?? throw new NotFoundException("Shift", shiftId);
        var register = await RegisterAsync(shift.RegisterId, ct);
        var sales = await db.Set<PosSale>().AsNoTracking().Include(s => s.Lines).Where(s => s.ShiftId == shiftId).ToListAsync(ct);
        var normal = sales.Where(s => s.RefundOfId == null).ToList();
        var refunds = sales.Where(s => s.RefundOfId != null).ToList();
        var lines = sales.SelectMany(s => s.Lines).ToList();
        var items = await inventory.GetItemsAsync(lines.Select(l => l.ItemId).Distinct(), ct);
        var top = lines.GroupBy(l => l.ItemId).Select(g => new ZReportItem(g.Key, items[g.Key].Sku, items[g.Key].NameEn, items[g.Key].NameAr, g.Sum(l => l.Quantity),
            g.Sum(l => l.Amount))).OrderByDescending(x => x.Amount).Take(10).ToList();
        var expected = shift.ExpectedCash ?? shift.OpeningFloat + await CashTakenAsync(shift.Id, ct);
        return new ZReport(ToDto(shift, register.Code), normal.Count, refunds.Count, normal.Sum(s => s.Total + s.DiscountTotal), normal.Sum(s => s.DiscountTotal),
            -refunds.Sum(s => s.Total), sales.Sum(s => s.Total), sales.Sum(s => s.CashAmount - s.ChangeGiven), sales.Sum(s => s.CardAmount), shift.OpeningFloat,
            expected, shift.CountedCash, shift.Difference, sales.Sum(s => s.Cost), top);
    }

    private async Task<decimal> CashTakenAsync(Guid shiftId, CancellationToken ct) =>
        await db.Set<PosSale>().Where(s => s.ShiftId == shiftId).SumAsync(s => (decimal?)(s.CashAmount - s.ChangeGiven), ct) ?? 0;

    private async Task<(PosShift Shift, PosRegister Register)> OpenShiftAsync(Guid shiftId, CancellationToken ct)
    {
        var shift = await db.Set<PosShift>().SingleOrDefaultAsync(s => s.Id == shiftId, ct) ?? throw new NotFoundException("Shift", shiftId);
        var register = await RegisterAsync(shift.RegisterId, ct);
        if (shift.Status != ShiftStatus.Open) throw new ConflictException("sal.shift_closed", "This shift is closed.", "هذه الوردية مغلقة.");
        return (shift, register);
    }

    private async Task<PosRegister> RegisterAsync(Guid id, CancellationToken ct) =>
        await db.Set<PosRegister>().SingleOrDefaultAsync(x => x.Id == id && x.CompanyId == tenant.RequireCompanyId(), ct) ?? throw new NotFoundException("Register", id);

    internal static ShiftDto ToDto(PosShift s, string registerCode) => new(s.Id, s.ShiftNo, s.RegisterId, registerCode, s.CashierUserId, s.OpenedAt, s.OpeningFloat,
        s.Status.ToString(), s.ClosedAt, s.BusinessDate, s.ExpectedCash, s.CountedCash, s.Difference);

    private static string? Clean(string? v) => string.IsNullOrWhiteSpace(v) ? null : v.Trim();
}

internal static class PosEndpoints
{
    public static void Map(IEndpointRouteBuilder app)
    {
        var g = app.MapGroup("/api/sales/pos").WithTags("Point of sale").RequireAuthorization();
        g.MapGet("/registers", async (ErpDbContext db, ITenantContext t, CancellationToken ct) =>
        {
            var registers = await db.Set<PosRegister>().AsNoTracking().Where(r => r.CompanyId == t.RequireCompanyId()).OrderBy(r => r.Code).ToListAsync(ct);
            var ids = registers.Select(r => r.Id).ToList();
            var open = await db.Set<PosShift>().AsNoTracking().Where(s => ids.Contains(s.RegisterId) && s.Status == ShiftStatus.Open)
                .ToDictionaryAsync(s => s.RegisterId, s => s.Id, ct);
            return registers.Select(r => new RegisterDto(r.Id, r.Code, r.NameEn, r.NameAr, r.WarehouseId, r.CashAccountId, r.CardAccountId, r.IsActive,
                open.TryGetValue(r.Id, out var s) ? s : null));
        }).RequirePermission(SalesPermissions.PosSell);
        g.MapGet("/catalog", (IInventoryQueries inv, CancellationToken ct) => inv.GetCatalogAsync(ct)).RequirePermission(SalesPermissions.PosSell);
        g.MapPost("/registers", async (RegisterRequest r, PosService s, CancellationToken ct) => (await s.SaveRegisterAsync(null, r, ct)).Id)
            .RequirePermission(SalesPermissions.PosManage);
        g.MapPut("/registers/{id:guid}", async (Guid id, RegisterRequest r, PosService s, CancellationToken ct) => (await s.SaveRegisterAsync(id, r, ct)).Id)
            .RequirePermission(SalesPermissions.PosManage);

        g.MapGet("/shifts", async (ErpDbContext db, ITenantContext t, CancellationToken ct, Guid? registerId = null) =>
            await (from s in db.Set<PosShift>().AsNoTracking()
                   join r in db.Set<PosRegister>() on s.RegisterId equals r.Id
                   where r.CompanyId == t.RequireCompanyId() && (registerId == null || s.RegisterId == registerId)
                   orderby s.OpenedAt descending
                   select PosService.ToDto(s, r.Code)).Take(200).ToListAsync(ct)).RequirePermission(SalesPermissions.PosSell);
        g.MapPost("/shifts", async (OpenShiftRequest r, PosService s, ErpDbContext db, CancellationToken ct) =>
        {
            var shift = await s.OpenShiftAsync(r, ct);
            var code = await db.Set<PosRegister>().Where(x => x.Id == shift.RegisterId).Select(x => x.Code).SingleAsync(ct);
            return PosService.ToDto(shift, code);
        }).RequirePermission(SalesPermissions.PosSell);
        g.MapPost("/shifts/{id:guid}/close", async (Guid id, CloseShiftRequest r, PosService s, CancellationToken ct) =>
        {
            await s.CloseShiftAsync(id, r, ct);
            return await s.ZReportAsync(id, ct);
        }).RequirePermission(SalesPermissions.PosSell);
        g.MapGet("/shifts/{id:guid}/z-report", (Guid id, PosService s, CancellationToken ct) => s.ZReportAsync(id, ct)).RequirePermission(SalesPermissions.PosSell);

        g.MapPost("/sales", async (PosSaleRequest r, PosService s, IInventoryQueries inv, ErpDbContext db, CancellationToken ct) =>
            await DtoAsync(await s.SellAsync(r, ct), inv, db, ct)).RequirePermission(SalesPermissions.PosSell);
        g.MapPost("/refunds", async (PosRefundRequest r, PosService s, IInventoryQueries inv, ErpDbContext db, CancellationToken ct) =>
            await DtoAsync(await s.RefundAsync(r, ct), inv, db, ct)).RequirePermission(SalesPermissions.PosSell);
        g.MapGet("/sales/by-receipt/{receiptNo}", async (string receiptNo, IInventoryQueries inv, ErpDbContext db, CancellationToken ct) =>
        {
            var sale = await db.Set<PosSale>().AsNoTracking().Include(s => s.Lines).SingleOrDefaultAsync(s => s.ReceiptNo == receiptNo.ToUpper(), ct)
                       ?? throw new NotFoundException("POS sale", receiptNo);
            return await DtoAsync(sale, inv, db, ct);
        }).RequirePermission(SalesPermissions.PosSell);
    }

    private static async Task<PosSaleDto> DtoAsync(PosSale s, IInventoryQueries inv, ErpDbContext db, CancellationToken ct)
    {
        var items = await inv.GetItemsAsync(s.Lines.Select(l => l.ItemId), ct);
        var refunded = s.RefundOfId is null
            ? (await (from l in db.Set<PosSaleLine>() join r in db.Set<PosSale>() on l.PosSaleId equals r.Id where r.RefundOfId == s.Id select new { l.RefundOfLineId, l.Quantity })
                .ToListAsync(ct)).GroupBy(x => x.RefundOfLineId).ToDictionary(g => g.Key!.Value, g => -g.Sum(x => x.Quantity))
            : [];
        return new PosSaleDto(s.Id, s.ReceiptNo, s.ClientId, s.ShiftId, s.SoldAt, s.CustomerName, s.Total, s.DiscountTotal, s.CashAmount, s.CardAmount, s.ChangeGiven,
            s.RefundOfId is not null,
            s.Lines.OrderBy(l => l.LineNo).Select(l => new PosSaleLineDto(l.Id, l.LineNo, l.ItemId, items[l.ItemId].Sku, items[l.ItemId].NameEn, items[l.ItemId].NameAr,
                l.Quantity, l.UnitPrice, l.DiscountPercent, l.Amount, l.Quantity - refunded.GetValueOrDefault(l.Id))).ToList());
    }
